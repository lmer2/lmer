"""Push allow-list grammar parity across the standalone mirrors (#116).

LMER_PUSH_ALLOW_LIST is enforced at three points:

- src/lmer_cli/gates.py run_push_gate — the source of truth;
- hooks/pc.py push_allowed — stdlib-only in-container hook that cannot
  import lmer_cli (same standalone constraint as container/clone_and_exec.py,
  cf. lmer_cli/tokens.py);
- the POSIX-sh pre-push hook generated by the heredoc in hooks/install.sh.

The latter two DUPLICATE the extended grammar (`repo` for branch refs only,
`repo|refpattern` for fnmatch against the fully-qualified ref; malformed
entries ignored fail-closed). Per the mirrored-logic convention
(tests/test_harness_runners.py, tests/test_masterplan_provisioning.py), a
duplicated implementation is acceptable only with a guard test — this module
is that guard and the resolution mechanism for issue #116: every live
implementation must return the same allow/deny verdict over the shared case
table below, so the ref-scoped rule cannot be bypassed by whichever
enforcement point an agent happens to hit.

Two rules sit alongside the entry grammar and are guarded here too:

- **Ref deletion is never authorized** — gates.py refuses an empty-`<src>`
  refspec, the pre-push hook refuses git's deletion line. Neither can be
  granted by an allow-list entry.
- **Push-by-URL matches ANCHORED** — when git was handed a URL instead of a
  configured remote, the repo half must name the URL's `host/path` or its
  `host`, not merely appear inside it. hooks/pc.py has no
  push-by-URL path (its URL is always `git remote get-url --push origin`) and no
  deletion path (its ref is always `git branch --show-current`), so those
  two rules are parity-checked across gates.py and the generated hook only.

**A parity suite that only cross-compares the mirrors is blind to a bug they
SHARE** — which is exactly how the last-`@` userinfo strip survived: all three
copies normalized `https://evil.example.com/x@github.com/group/project` to
`github.com/group/project`, so they agreed, and agreement was the whole test.
Two guards close that hole: `URL_IDENTITIES` states the expected `host/path`
for each URL as a hand-written constant (derived from what `urlsplit` and git
itself say, not from any implementation), and
`test_the_authorized_host_is_the_host_git_would_dial` asserts the PROPERTY a
shared bug violates — no implementation may authorize an entry naming a host
other than the one git dials.
"""

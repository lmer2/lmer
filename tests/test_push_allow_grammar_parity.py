def test_gate_checks_the_pushurl_not_the_fetch_url(tmp_path, monkeypatch, capsys):
    """A configured `remote.<name>.pushurl` is where git pushes; the gate
    must authorize THAT url.

    Driven against a real repository and real `git remote get-url` — a
    stubbed run_command cannot prove the `--push` flag is passed, which is
    precisely why the defect survived the mirror-vs-mirror parity suite.
    """
    repo = tmp_path / "repo"
    repo.mkdir()
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    subprocess.run(["git", "remote", "add", "origin", GITHUB_MIRROR],
                   cwd=repo, check=True)
    subprocess.run(["git", "config", "remote.origin.pushurl",
                    "https://evil.example.invalid/x.git"], cwd=repo, check=True)

    def verdict(allow):
        monkeypatch.setenv("LMER_PUSH_ALLOW_LIST", allow)
        gate = GateSystem()
        gate.project_root = repo  # run_command runs with cwd=project_root
        gate.run_commit_gate = lambda: True
        return gate.run_push_gate(ref="refs/heads/main", remote="origin")

    # The fetch url is on the allow list; the PUSH url is not.
    assert verdict("github.com/group/project") is False
    # ...and naming the push url authorizes it, proving the gate read that
    # url rather than simply failing on everything.
    assert verdict("evil.example.invalid/x") is True

    # The generated hook is fed the push url by git itself ($2), so it is
    # right by construction — pin that it stays keyed on $2.
    hook = tmp_path / "pre-push"
    hook.write_text(PRE_PUSH_BODY)
    result = subprocess.run(
        ["sh", str(hook), "origin", "https://evil.example.invalid/x.git"],
        input=f"refs/heads/main {LOCAL_SHA} refs/heads/main {REMOTE_SHA}\n",
        cwd=repo,
        env={**os.environ,
             "LMER_PUSH_ALLOW_LIST": "github.com/group/project|refs/heads/*"},
        capture_output=True,
        text=True,
    )
    assert result.returncode == 1, result.stdout


def test_detached_head_refuses_instead_of_matching_refs_heads_star(
        tmp_path, monkeypatch, capsys):
    """`git branch --show-current` exits 0 with EMPTY stdout on a detached
    HEAD. Interpolating that gives the literal "refs/heads/", and
    `fnmatch("refs/heads/", "refs/heads/*")` is True — `*` matches empty —
    so a bare allow-list entry would authorize a ref naming no branch.
    Both python mirrors must refuse instead."""
    monkeypatch.setenv("LMER_PUSH_ALLOW_LIST", "group/project")
    gate = GateSystem()

    def fake_run_command(command, check=True):
        if command[:4] == ["git", "remote", "get-url", "--push"]:
            return 0, GITLAB_SSH + "\n", ""
        if command[:3] == ["git", "branch", "--show-current"]:
            return 0, "\n", ""  # detached HEAD
        return 0, "", ""

    gate.run_command = fake_run_command
    gate.run_commit_gate = lambda: True
    assert gate.run_push_gate(ref=None, remote="origin") is False
    assert "detached HEAD" in capsys.readouterr().out

    # hooks/pc.py's push_allowed() has the same shape; its caller is what
    # must not hand it an empty branch (see main()). The URL is a real repo
    # URL (granted by the `group/project` entry through the host-less rule)
    # rather than the bare entry text: since #107 the repo half is parsed
    # into host+path instead of substring-matched, so `group/project` as a
    # URL would now be read as host `group`, and this test would fail for a
    # reason that has nothing to do with the empty ref it exists to pin.
    assert PC_HOOK.push_allowed(GITLAB_SSH, "") is True, (
        "push_allowed itself still normalizes '' — the guard belongs in the "
        "caller, and this pins which side owns it"
    )
    source = PC_HOOK_PATH.read_text()
    assert "if not branch:" in source, (
        "hooks/pc.py must refuse an empty `git branch --show-current` before "
        "calling push_allowed"
    )


def test_pc_hook_pushes_the_remote_it_authorized():
    """hooks/pc.py must push to the remote whose URL it gated on.

    It authorizes `git remote get-url --push origin`, so the push has to
    name `origin` explicitly: a bare `git push` resolves its remote through
    branch.<name>.pushRemote → remote.pushDefault → branch.<name>.remote,
    and either of the first two sends the commit to a remote the allow-list
    check never looked at — the same authorize-one-target-dial-another
    shape as gating the fetch url instead of the push url.
    """
    source = PC_HOOK_PATH.read_text()
    assert '["git", "push", "origin", branch]' in source, (
        "hooks/pc.py must push to the remote and ref it authorized "
        "(`git push origin <branch>`)"
    )
    assert '["git", "push"])' not in source, (
        "a bare `git push` can be redirected by remote.pushDefault / "
        "branch.<name>.pushRemote to a remote the gate never checked"
    )



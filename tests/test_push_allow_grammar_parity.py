def test_pre_push_hook_gates_push_by_url_via_arg2(tmp_path):
    """Push-by-URL: git passes the URL as $2 with no configured remote —
    the hook must evaluate the allow list against it, both directions."""
    repo = tmp_path / "repo"
    repo.mkdir()
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    hook = tmp_path / "pre-push"
    hook.write_text(PRE_PUSH_BODY)
    stdin = f"refs/heads/main {LOCAL_SHA} refs/heads/main {REMOTE_SHA}\n"

    def push_by_url(url, allow="github.com/group/project"):
        return subprocess.run(
            ["sh", str(hook), url, url],
            input=stdin,
            cwd=repo,
            env={**os.environ, "LMER_PUSH_ALLOW_LIST": allow},
            capture_output=True,
            text=True,
        ).returncode

    assert push_by_url(GITHUB_MIRROR) == 0
    assert push_by_url("https://github.com/attacker/repo.git") == 1
    # The entry must name the host on this branch: a path-only grant would
    # authorize the same path on any forge.
    assert push_by_url(GITHUB_MIRROR, allow="group/project") == 1

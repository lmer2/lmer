def _load_pc_hook():
    """Load hooks/pc.py by path — it is not an importable package module."""
    spec = importlib.util.spec_from_file_location("lmer_pc_hook", PC_HOOK_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _extract_pre_push_body():
    """Pull the generated pre-push hook out of install.sh's heredoc."""
    text = INSTALL_SH_PATH.read_text()
    marker = "cat > \"$GLOBAL_DIR/.git/hooks/pre-push\" << 'EOF'\n"
    start = text.index(marker) + len(marker)
    end = text.index("\nEOF\n", start)
    return text[start:end + 1]


PC_HOOK = _load_pc_hook()
PRE_PUSH_BODY = _extract_pre_push_body()


def gates_verdict(allow, url, ref, monkeypatch):
    """Allow/deny from the source of truth, gates.py run_push_gate.

    git calls are stubbed (remote get-url -> `url`) and the trailing
    commit-gate run is short-circuited so the return value IS the
    allow-list verdict.
    """
    monkeypatch.setenv("LMER_PUSH_ALLOW_LIST", allow)
    gate = GateSystem()

    def fake_run_command(command, check=True):
        # `--push` is mandatory: git pushes to remote.<name>.pushurl when it
        # is set, so gating the bare (fetch) url authorizes one repository
        # and pushes to another. Asserted for real against a configured
        # pushurl in test_gate_checks_the_pushurl_not_the_fetch_url.
        if command[:4] == ["git", "remote", "get-url", "--push"]:
            return 0, url + "\n", ""
        if command[:3] == ["git", "remote", "get-url"]:
            raise AssertionError(
                "run_push_gate must resolve the remote with `get-url --push`"
            )
        return 0, "", ""

    gate.run_command = fake_run_command
    gate.run_commit_gate = lambda: True
    return gate.run_push_gate(ref=ref, remote="origin")


def pc_verdict(allow, url, ref):
    """Allow/deny from the in-container hook's mirrored push_allowed()."""
    return PC_HOOK.push_allowed(url, ref, allow)


def bash_verdict(allow, url, ref, tmp_path):
    """Allow/deny from the generated pre-push hook, run under plain sh
    in a scratch repo whose origin points at `url`."""
    repo = tmp_path / "repo"
    repo.mkdir()
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    subprocess.run(["git", "remote", "add", "origin", url], cwd=repo, check=True)

    hook = tmp_path / "pre-push"
    hook.write_text(PRE_PUSH_BODY)

    # A real-looking local sha: an all-zero one is git's DELETION marker,
    # which the hook refuses outright (test_ref_deletion_is_refused_*).
    stdin = f"{ref} {LOCAL_SHA} {ref} {REMOTE_SHA}\n"
    env = {**os.environ, "LMER_PUSH_ALLOW_LIST": allow}
    result = subprocess.run(
        ["sh", str(hook), "origin", url],
        input=stdin,
        cwd=repo,
        env=env,
        capture_output=True,
        text=True,
    )
    return result.returncode == 0


def test_pre_push_hook_is_posix_sh(tmp_path):
    """The generated hook declares /bin/sh and parses under `sh -n`."""
    assert PRE_PUSH_BODY.startswith("#!/bin/sh\n")
    hook = tmp_path / "pre-push"
    hook.write_text(PRE_PUSH_BODY)
    result = subprocess.run(
        ["sh", "-n", str(hook)], capture_output=True, text=True
    )
    assert result.returncode == 0, result.stderr


@pytest.mark.parametrize("allow,url,ref,expected", CASES)
def test_all_implementations_agree(allow, url, ref, expected,
                                   tmp_path, monkeypatch, capsys):
    verdicts = {
        "gates.py": gates_verdict(allow, url, ref, monkeypatch),
        "hooks/pc.py": pc_verdict(allow, url, ref),
        "install.sh pre-push": bash_verdict(allow, url, ref, tmp_path),
    }
    assert verdicts == {name: expected for name in verdicts}, (
        f"verdict divergence for entry={allow!r} url={url!r} ref={ref!r}: "
        f"{verdicts} (expected {expected})"
    )


@pytest.mark.parametrize("bare,qualified", [
    ("main", "refs/heads/main"),
    ("feature-x", "refs/heads/feature-x"),
])
def test_bare_branch_names_normalize_only_where_the_input_is_a_branch(
        bare, qualified, monkeypatch, capsys):
    """pc.py qualifies bare names as refs/heads/<name> — its only caller
    feeds it `git branch --show-current`, so the input is a branch by
    construction. gates.py REFUSES explicit bare names: its ref parameter
    is user-supplied (`gate-push --ref`), where a short name is ambiguous
    (git resolves `v1.2.3` to refs/tags/v1.2.3 when such a tag exists), so
    normalizing there would authorize the wrong ref class. The bash hook
    never sees bare names — git feeds pre-push fully qualified refs.
    """
    allow = "group/project"
    assert pc_verdict(allow, GITLAB_SSH, bare) == pc_verdict(
        allow, GITLAB_SSH, qualified
    ) == True
    assert gates_verdict(allow, GITLAB_SSH, bare, monkeypatch) == False
    assert gates_verdict(allow, GITLAB_SSH, qualified, monkeypatch) == True


@pytest.mark.parametrize("allow", [
    "group/project",                    # bare grant, branch refs
    "group/project|refs/tags/*",        # the release-flow tag grant
    "group/project|refs/heads/*, group/project|refs/tags/*",
])
def test_ref_deletion_is_refused_by_every_implementation(allow, tmp_path,
                                                         monkeypatch, capsys):
    """Deleting a ref is never authorized, however wide the grant.

    A deletion is at least as destructive as the force push both mirrors
    already refuse, and the release flow declares published tags immutable
    (never deleted, never re-pointed). gates.py sees it as an empty `<src>`
    refspec (`:refs/tags/v0.5.0`); the pre-push hook sees git's deletion
    line — `(delete)` as the local ref with an all-zero local sha.
    """
    assert gates_verdict(allow, GITLAB_SSH, ":refs/tags/v0.5.0", monkeypatch) is False
    assert gates_verdict(allow, GITLAB_SSH, ":refs/heads/main", monkeypatch) is False

    repo = tmp_path / "repo"
    repo.mkdir()
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True)
    hook = tmp_path / "pre-push"
    hook.write_text(PRE_PUSH_BODY)

    def hook_verdict(stdin):
        return subprocess.run(
            ["sh", str(hook), "origin", GITLAB_SSH],
            input=stdin,
            cwd=repo,
            env={**os.environ, "LMER_PUSH_ALLOW_LIST": allow},
            capture_output=True,
            text=True,
        )

    for ref in ("refs/tags/v0.5.0", "refs/heads/main"):
        # git's shape for a deletion, and the same line with only the
        # all-zero local sha to prove neither signal alone is relied on.
        for line in (f"(delete) {ZERO_SHA} {ref} {REMOTE_SHA}\n",
                     f"{ref} {ZERO_SHA} {ref} {REMOTE_SHA}\n"):
            result = hook_verdict(line)
            assert result.returncode == 1, result.stdout
            assert "deletion is never approved" in result.stdout



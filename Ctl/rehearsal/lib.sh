#!/bin/bash
# lib.sh — shared helpers for the release rehearsal rig (see README.md in
# this directory; that document is the frozen design).
#
# Sourced by stand-up.sh and by the later rehearsal scripts (negative
# tag-verification tests, leg-2 dry run), which only consume what is
# defined here:
#   - production-target guard (offline; runs before any network call)
#   - GitHub API wrapper + Actions run/job polling
#   - TestPyPI file listing, GitHub release lookup
#   - evidence writer / parser / offline verifier
#
# Also executable directly for the offline evidence re-check:
#   Ctl/rehearsal/lib.sh --verify-evidence <file>
#
# No rig identity is hard-coded here: repo, project, environment, and
# credentials all arrive via LMER_REHEARSAL_* variables (rig.env).

REHEARSAL_LIB_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
REHEARSAL_ROOT=${REHEARSAL_ROOT:-$(cd -- "${REHEARSAL_LIB_DIR}/../.." && pwd)}

REHEARSAL_GITHUB_API=${REHEARSAL_GITHUB_API:-https://api.github.com}
REHEARSAL_TESTPYPI_URL=${REHEARSAL_TESTPYPI_URL:-https://test.pypi.org}

# Same path as production, deliberately (README: trusted-publisher binding).
REHEARSAL_WORKFLOW_PATH=".github/workflows/release.yml"
REHEARSAL_PUBLISH_JOB="publish-pypi"

# The rehearsal-only credential variables required by rig-touching modes
# (README: Credential isolation). R14: when any is absent, rig-touching
# modes SKIP-CLEAN. LMER_REHEARSAL_TESTPYPI_TOKEN is deliberately NOT
# listed: no rig script reads it — TestPyPI verification uses the tokenless
# read-only JSON API and publishing goes through the trusted publisher
# (OIDC) — so it must not gate anything.
REHEARSAL_ENV_VARS=(
    LMER_REHEARSAL_GITHUB_TOKEN
    LMER_REHEARSAL_SIGNING_KEY
)

# Evidence scenarios (README: Evidence format).
REHEARSAL_SCENARIOS="negative-unsigned-tag negative-wrong-signer negative-not-main-head leg2-dry-run"

rehearsal_err() {
    printf '%s\n' "$*" >&2
}

rehearsal_refuse() {
    printf 'REFUSED: %s\n' "$*" >&2
    return 1
}

# ---------------------------------------------------------------------------
# Production-target guard — fully offline, must run before any network call.
# The rig is rehearsal-only: it never touches the production mirror
# (lmer2/lmer), the production PyPI project (lmer), pypi.org, the
# production release PAT, or the production release signing key.
# ---------------------------------------------------------------------------

rehearsal_guard_repo() {
    local repo="${1:-}"
    [[ -z "$repo" ]] && return 0
    local lower=${repo,,}
    local name=${lower##*/}
    if [[ "$lower" == "lmer2/lmer" || "$name" == "lmer" ]]; then
        rehearsal_refuse "'$repo' is a production repo target; the rehearsal rig only touches its own scratch repo (e.g. <bot>/lmer-rehearsal)"
        return 1
    fi
    return 0
}

rehearsal_guard_project() {
    local project="${1:-}"
    [[ -z "$project" ]] && return 0
    if [[ "${project,,}" == "lmer" ]]; then
        rehearsal_refuse "'$project' is the production PyPI project name; the rehearsal project must be unmistakably non-production (e.g. lmer-rehearsal)"
        return 1
    fi
    return 0
}

rehearsal_guard_url() {
    local url="${1:-}"
    [[ -z "$url" ]] && return 0
    local host=${url#*://}
    host=${host%%[/:]*}
    host=${host,,}
    case "$host" in
        test.pypi.org)
            return 0
            ;;
        pypi.org|*.pypi.org)
            rehearsal_refuse "'$host' is production PyPI; the rehearsal rig only talks to test.pypi.org"
            return 1
            ;;
    esac
    return 0
}

rehearsal_guard_credentials() {
    # A rehearsal shell must not carry production release credentials at
    # all — rig credentials are rehearsal-only by name (LMER_REHEARSAL_*),
    # and the presence of a production release variable means this
    # environment could reach production. Refuse outright.
    local v
    for v in LMER_RELEASE_SIGNING_KEY LMER_RELEASE_GITHUB_TOKEN LMER_RELEASE_GITHUB_PAT RELEASE_GITHUB_PAT; do
        if [[ -n "${!v:-}" ]]; then
            rehearsal_refuse "production release credential variable $v is set; the rehearsal rig never runs with production credentials in its environment"
            return 1
        fi
    done
    # The throwaway rehearsal key must never be the production key mount
    # (CONTAINER_RELEASE_SIGNING_KEY_PATH in src/lmer_cli/mounts.py).
    case "${LMER_REHEARSAL_SIGNING_KEY:-}" in
        /release-signing-key|/release-signing-key/*)
            rehearsal_refuse "LMER_REHEARSAL_SIGNING_KEY points at the production release key mount (/release-signing-key); use a throwaway key generated by stand-up.sh"
            return 1
            ;;
    esac
    return 0
}

# rehearsal_guard <repo> <project> [url ...] — the whole guard in one call.
rehearsal_guard() {
    local repo="${1:-}" project="${2:-}"
    rehearsal_guard_credentials || return 1
    rehearsal_guard_repo "$repo" || return 1
    rehearsal_guard_project "$project" || return 1
    if (($# > 2)); then
        shift 2
        local url
        for url in "$@"; do
            rehearsal_guard_url "$url" || return 1
        done
    fi
    return 0
}


# R14 skip-clean — rig-touching modes with no rig env vars do nothing,
# loudly and successfully, so the scripts verify in a sandbox.
# ---------------------------------------------------------------------------

# Print the names of the unset rig credential variables, one per line.
rehearsal_missing_env() {
    local v
    for v in "${REHEARSAL_ENV_VARS[@]}"; do
        if [[ -z "${!v:-}" ]]; then
            printf '%s\n' "$v"
        fi
    done
    return 0
}

rehearsal_skip_clean() {
    local mode="$1"
    shift
    echo "SKIP-CLEAN (${mode}): rehearsal rig env vars absent — nothing to touch."
    echo "  missing: $*"
    echo "  To enable the rig, copy Ctl/rehearsal/rig.env.example to Ctl/rehearsal/rig.env and fill it in."
    echo "  Exiting 0 by design (R14): the rig is optional in sandboxes."
}

# ---------------------------------------------------------------------------
# GitHub API (Actions run/job polling, release lookup)
# ---------------------------------------------------------------------------

# The Authorization header rides a 0600 file (curl -H @file), never argv —
# a command line is world-readable via /proc/*/cmdline, and the pollers
# re-invoke curl every few seconds. The rig scripts call
# rehearsal_gh_auth_setup once, in the parent shell, before their first
# API call (rehearsal_gh_api mostly runs inside command substitutions,
# where a lazily created path could not persist), and remove the file
# from their EXIT traps via rehearsal_gh_auth_cleanup.
REHEARSAL_GH_AUTH_FILE=""

rehearsal_gh_auth_cleanup() {
    if [[ -n "$REHEARSAL_GH_AUTH_FILE" ]]; then
        rm -f -- "$REHEARSAL_GH_AUTH_FILE"
        REHEARSAL_GH_AUTH_FILE=""
    fi
}

# rehearsal_gh_auth_setup — create-or-refresh the header file; idempotent
# (reuses the existing file, so subshells inherit one shared path).
rehearsal_gh_auth_setup() {
    if [[ -z "$REHEARSAL_GH_AUTH_FILE" || ! -f "$REHEARSAL_GH_AUTH_FILE" ]]; then
        REHEARSAL_GH_AUTH_FILE=$(mktemp) || return 1
        chmod 600 "$REHEARSAL_GH_AUTH_FILE"
    fi
    printf 'Authorization: Bearer %s\n' "${LMER_REHEARSAL_GITHUB_TOKEN}" \
        > "$REHEARSAL_GH_AUTH_FILE"
}

# rehearsal_gh_api <METHOD> </path> [json-body]
rehearsal_gh_api() {
    local method="$1" path="$2" body="${3:-}"
    rehearsal_guard_credentials || return 1
    if [[ -z "${LMER_REHEARSAL_GITHUB_TOKEN:-}" ]]; then
        rehearsal_err "rehearsal_gh_api: LMER_REHEARSAL_GITHUB_TOKEN is not set"
        return 1
    fi
    rehearsal_gh_auth_setup || return 1
    local args=(
        -sS --fail
        -X "$method"
        -H "Accept: application/vnd.github+json"
        -H "@${REHEARSAL_GH_AUTH_FILE}"
        -H "X-GitHub-Api-Version: 2022-11-28"
    )
    if [[ -n "$body" ]]; then
        args+=(-H "Content-Type: application/json" -d "$body")
    fi
    curl "${args[@]}" "${REHEARSAL_GITHUB_API}${path}"
}

# rehearsal_json_get <dotted.path> — read JSON on stdin, print the value
# at the path ('' when absent). List indices are numeric path parts.
rehearsal_json_get() {
    python3 -c '
import json
import sys

obj = json.load(sys.stdin)
for part in sys.argv[1].split("."):
    if isinstance(obj, list):
        obj = obj[int(part)] if int(part) < len(obj) else None
    elif isinstance(obj, dict):
        obj = obj.get(part)
    else:
        obj = None
    if obj is None:
        break
print("" if obj is None else obj)
' "$1"
}

# rehearsal_json_string — JSON-encode stdin as a single string literal.
rehearsal_json_string() {
    python3 -c 'import json, sys; print(json.dumps(sys.stdin.read().rstrip("\n")))'
}

# rehearsal_find_run_for_tag <repo> <tag> — id of the newest release.yml
# run for the tag push ('' when none). Tag runs carry the tag name as
# head_branch.
rehearsal_find_run_for_tag() {
    local repo="$1" tag="$2"
    rehearsal_guard_repo "$repo" || return 1
    rehearsal_gh_api GET "/repos/${repo}/actions/runs?event=push&branch=${tag}" |
        python3 -c '
import json
import sys

wf_path = sys.argv[1]
for run in json.load(sys.stdin).get("workflow_runs", []):
    if run.get("path") == wf_path:
        print(run["id"])
        break
' "$REHEARSAL_WORKFLOW_PATH"
}

# rehearsal_poll_run <repo> <run-id> [timeout-s] [interval-s] — wait for
# an Actions run to complete; print its conclusion.
rehearsal_poll_run() {
    local repo="$1" run_id="$2" timeout="${3:-600}" interval="${4:-10}"
    rehearsal_guard_repo "$repo" || return 1
    local waited=0 body status
    while :; do
        body=$(rehearsal_gh_api GET "/repos/${repo}/actions/runs/${run_id}") || return 1
        status=$(printf '%s' "$body" | rehearsal_json_get status)
        if [[ "$status" == "completed" ]]; then
            printf '%s' "$body" | rehearsal_json_get conclusion
            return 0
        fi
        if (( waited >= timeout )); then
            rehearsal_err "rehearsal_poll_run: run ${run_id} still '${status}' after ${timeout}s"
            return 1
        fi
        sleep "$interval"
        waited=$(( waited + interval ))
    done
}

# rehearsal_rerun_run <repo> <run-id> [restart-timeout-s] [interval-s] —
# POST .../rerun, then wait until GitHub actually starts the new attempt
# (status leaves 'completed', or run_attempt increments past the pre-rerun
# value). Immediately after the POST the API can still serve the PREVIOUS
# attempt's completed status/conclusion; polling without this wait returns
# a stale conclusion (and acting on it can 403 a second rerun POST against
# a now-in-progress run).
rehearsal_rerun_run() {
    local repo="$1" run_id="$2" timeout="${3:-120}" interval="${4:-5}"
    rehearsal_guard_repo "$repo" || return 1
    local body prev_attempt status attempt waited=0
    body=$(rehearsal_gh_api GET "/repos/${repo}/actions/runs/${run_id}") || return 1
    prev_attempt=$(printf '%s' "$body" | rehearsal_json_get run_attempt)
    prev_attempt=${prev_attempt:-1}
    rehearsal_gh_api POST "/repos/${repo}/actions/runs/${run_id}/rerun" >/dev/null || return 1
    while :; do
        body=$(rehearsal_gh_api GET "/repos/${repo}/actions/runs/${run_id}") || return 1
        status=$(printf '%s' "$body" | rehearsal_json_get status)
        attempt=$(printf '%s' "$body" | rehearsal_json_get run_attempt)
        if [[ "$status" != "completed" ]]; then
            return 0
        fi
        if [[ "$attempt" =~ ^[0-9]+$ ]] && (( attempt > prev_attempt )); then
            return 0
        fi
        if (( waited >= timeout )); then
            rehearsal_err "rehearsal_rerun_run: run ${run_id} still reports the pre-rerun attempt (${prev_attempt}, completed) after ${timeout}s"
            return 1
        fi
        sleep "$interval"
        waited=$(( waited + interval ))
    done
}

# rehearsal_rig_workflow_fetch <repo> — the rig repo's committed release
# workflow (contents API, base64-decoded), for the drift guard's diff
# against the freshly derived output (README: Workflow derivation).
rehearsal_rig_workflow_fetch() {
    local repo="$1"
    rehearsal_guard_repo "$repo" || return 1
    rehearsal_gh_api GET "/repos/${repo}/contents/${REHEARSAL_WORKFLOW_PATH}" |
        python3 -c '
import base64
import json
import sys

doc = json.load(sys.stdin)
sys.stdout.write(base64.b64decode(doc["content"]).decode())
'
}

# rehearsal_run_jobs <repo> <run-id> — one "name<TAB>conclusion" per job.
rehearsal_run_jobs() {
    local repo="$1" run_id="$2"
    rehearsal_guard_repo "$repo" || return 1
    rehearsal_gh_api GET "/repos/${repo}/actions/runs/${run_id}/jobs" |
        python3 -c '
import json
import sys

for job in json.load(sys.stdin).get("jobs", []):
    print(job["name"], job.get("conclusion") or job.get("status") or "", sep="\t")
'
}

# rehearsal_release_lookup <repo> <tag> — the GitHub release JSON for a
# tag (non-zero when absent).
rehearsal_release_lookup() {
    local repo="$1" tag="$2"
    rehearsal_guard_repo "$repo" || return 1
    rehearsal_gh_api GET "/repos/${repo}/releases/tags/${tag}"
}


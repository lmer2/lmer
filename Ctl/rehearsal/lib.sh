# rehearsal_testpypi_files <project> <version> — filenames published on
# TestPyPI for a release (read-only JSON API, no token needed).
rehearsal_testpypi_files() {
    local project="$1" version="$2"
    rehearsal_guard_project "$project" || return 1
    rehearsal_guard_url "$REHEARSAL_TESTPYPI_URL" || return 1
    curl -sS --fail "${REHEARSAL_TESTPYPI_URL}/pypi/${project}/${version}/json" |
        python3 -c '
import json
import sys

for entry in json.load(sys.stdin).get("urls", []):
    print(entry["filename"])
'
}

# rehearsal_testpypi_project_exists <project> — 0 iff the project has at
# least one release visible on TestPyPI.
rehearsal_testpypi_project_exists() {
    local project="$1"
    rehearsal_guard_project "$project" || return 1
    rehearsal_guard_url "$REHEARSAL_TESTPYPI_URL" || return 1
    curl -sS --fail -o /dev/null "${REHEARSAL_TESTPYPI_URL}/pypi/${project}/json"
}

# ---------------------------------------------------------------------------
# Evidence — one markdown file per rehearsal run, prose header plus a
# single fenced yaml block (README: Evidence format).
# ---------------------------------------------------------------------------

# rehearsal_release_job_order — job names of the production release
# workflow in definition order. Parsed from the workflow so the evidence
# verifier's "failed_job precedes publish-pypi" check tracks reality;
# falls back to the known order when the file is absent.
rehearsal_release_job_order() {
    local wf="${REHEARSAL_ROOT}/${REHEARSAL_WORKFLOW_PATH}"
    if [[ -f "$wf" ]]; then
        awk '
            /^jobs:[[:space:]]*$/ { injobs = 1; next }
            injobs && /^[^[:space:]#]/ { injobs = 0 }
            injobs && /^  [A-Za-z0-9_-]+:[[:space:]]*$/ {
                name = $1
                sub(/:$/, "", name)
                print name
            }
        ' "$wf"
    else
        printf '%s\n' verify-tag-signature verify-version checks build \
            publish-pypi github-release
    fi
}

# rehearsal_evidence_write field=value ... — write an evidence file and
# print its path. Fields mirror the README yaml block; recorded_at and
# the filename timestamp are supplied here. failed_job is optional
# (negatives only). The writer is permissive; rehearsal_verify_evidence
# is the strict end.
rehearsal_evidence_write() {
    local scenario="" rig_repo="" rig_project="" tag="" tag_sha=""
    local workflow_run_id="" workflow_run_url="" expected_conclusion=""
    local recorded_conclusion="" failed_job="" published="" derive_check=""
    local kv
    for kv in "$@"; do
        case "$kv" in
            scenario=*)            scenario=${kv#*=} ;;
            rig_repo=*)            rig_repo=${kv#*=} ;;
            rig_project=*)         rig_project=${kv#*=} ;;
            tag=*)                 tag=${kv#*=} ;;
            tag_sha=*)             tag_sha=${kv#*=} ;;
            workflow_run_id=*)     workflow_run_id=${kv#*=} ;;
            workflow_run_url=*)    workflow_run_url=${kv#*=} ;;
            expected_conclusion=*) expected_conclusion=${kv#*=} ;;
            recorded_conclusion=*) recorded_conclusion=${kv#*=} ;;
            failed_job=*)          failed_job=${kv#*=} ;;
            published=*)           published=${kv#*=} ;;
            derive_check=*)        derive_check=${kv#*=} ;;
            *)
                rehearsal_err "rehearsal_evidence_write: unknown field '${kv%%=*}'"
                return 2
                ;;
        esac
    done
    if [[ -z "$scenario" ]]; then
        rehearsal_err "rehearsal_evidence_write: scenario= is required"
        return 2
    fi
    local recorded_at stamp dir file
    recorded_at=$(date -u +%Y-%m-%dT%H:%M:%SZ)
    stamp=$(date -u +%Y%m%dT%H%M%SZ)
    dir=${REHEARSAL_EVIDENCE_DIR:-${REHEARSAL_ROOT}/docs/rehearsal}
    mkdir -p "$dir"
    file="${dir}/evidence-${stamp}-${scenario}.md"
    {
        printf '# Rehearsal evidence: %s\n\n' "$scenario"
        printf 'Recorded by the lmer release rehearsal rig (Ctl/rehearsal). Re-check\n'
        printf 'offline with `Ctl/rehearsal/lib.sh --verify-evidence <this file>`.\n\n'
        printf '```yaml\n'
        printf 'scenario: %s\n' "$scenario"
        printf 'rig_repo: %s\n' "$rig_repo"
        printf 'rig_project: %s\n' "$rig_project"
        printf 'tag: %s\n' "$tag"
        printf 'tag_sha: %s\n' "$tag_sha"
        printf 'workflow_run_id: %s\n' "$workflow_run_id"
        printf 'workflow_run_url: %s\n' "$workflow_run_url"
        printf 'expected_conclusion: %s\n' "$expected_conclusion"
        printf 'recorded_conclusion: %s\n' "$recorded_conclusion"
        if [[ -n "$failed_job" ]]; then
            printf 'failed_job: %s\n' "$failed_job"
        fi
        printf 'published: %s\n' "$published"
        printf 'recorded_at: %s\n' "$recorded_at"
        printf 'derive_check: %s\n' "$derive_check"
        printf '```\n'
    } > "$file"
    printf '%s\n' "$file"
}

# rehearsal_evidence_yaml <file> — the contents of the fenced yaml block.
rehearsal_evidence_yaml() {
    awk '
        /^```yaml[[:space:]]*$/ { inblock = 1; next }
        /^```[[:space:]]*$/     { inblock = 0 }
        inblock
    ' "$1"
}

# rehearsal_evidence_get <file> <key> — value for a key in the yaml
# block, trailing comment stripped ('' when absent).
rehearsal_evidence_get() {
    local file="$1" key="$2"
    rehearsal_evidence_yaml "$file" |
        sed -n "s/^${key}:[[:space:]]*//p" |
        head -n 1 |
        sed 's/[[:space:]][[:space:]]*#.*$//; s/[[:space:]]*$//'
}

# rehearsal_verify_evidence <file> — the offline re-check (no network),
# exactly the README's rules: required fields present and well-formed,
# recorded_conclusion matches expected_conclusion, negative scenarios
# name a pre-publish failed_job and record published: false, and
# derive_check is pass.
rehearsal_verify_evidence() {
    local file="${1:?evidence file required}"
    if [[ ! -f "$file" ]]; then
        rehearsal_err "verify-evidence: no such file: $file"
        return 1
    fi

    local errors=0

    local scenario
    scenario=$(rehearsal_evidence_get "$file" scenario)
    local known=0 s
    for s in $REHEARSAL_SCENARIOS; do
        if [[ "$scenario" == "$s" ]]; then
            known=1
        fi
    done
    if (( ! known )); then
        rehearsal_err "verify-evidence: unknown scenario '${scenario}' (expected one of: ${REHEARSAL_SCENARIOS})"
        errors=$(( errors + 1 ))
    fi

    local field value
    for field in scenario rig_repo rig_project tag tag_sha workflow_run_id \
                 workflow_run_url expected_conclusion recorded_conclusion \
                 published recorded_at derive_check; do
        value=$(rehearsal_evidence_get "$file" "$field")
        if [[ -z "$value" ]]; then
            rehearsal_err "verify-evidence: missing required field '${field}'"
            errors=$(( errors + 1 ))
        fi
    done

    local tag_sha recorded_at expected recorded published derive_check failed_job
    tag_sha=$(rehearsal_evidence_get "$file" tag_sha)
    recorded_at=$(rehearsal_evidence_get "$file" recorded_at)
    expected=$(rehearsal_evidence_get "$file" expected_conclusion)
    recorded=$(rehearsal_evidence_get "$file" recorded_conclusion)
    published=$(rehearsal_evidence_get "$file" published)
    derive_check=$(rehearsal_evidence_get "$file" derive_check)
    failed_job=$(rehearsal_evidence_get "$file" failed_job)

    if [[ -n "$tag_sha" && ! "$tag_sha" =~ ^[0-9a-f]{40}$ ]]; then
        rehearsal_err "verify-evidence: tag_sha '${tag_sha}' is not 40 lowercase hex"
        errors=$(( errors + 1 ))
    fi
    if [[ -n "$recorded_at" && ! "$recorded_at" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$ ]]; then
        rehearsal_err "verify-evidence: recorded_at '${recorded_at}' is not UTC ISO-8601 (YYYY-MM-DDThh:mm:ssZ)"
        errors=$(( errors + 1 ))
    fi
    case "$expected" in
        success|failure|"") ;;
        *)
            rehearsal_err "verify-evidence: expected_conclusion '${expected}' is not success/failure"
            errors=$(( errors + 1 ))
            ;;
    esac
    if [[ "$recorded" != "$expected" ]]; then
        rehearsal_err "verify-evidence: recorded_conclusion '${recorded}' does not match expected_conclusion '${expected}'"
        errors=$(( errors + 1 ))
    fi
    case "$published" in
        true|false|"") ;;
        *)
            rehearsal_err "verify-evidence: published '${published}' is not true/false"
            errors=$(( errors + 1 ))
            ;;
    esac
    if [[ "$derive_check" != "pass" ]]; then
        rehearsal_err "verify-evidence: derive_check is '${derive_check}', must be 'pass'"
        errors=$(( errors + 1 ))
    fi

    if [[ "$scenario" == negative-* ]]; then
        if [[ "$expected" != "failure" ]]; then
            rehearsal_err "verify-evidence: negative scenario must expect failure (got '${expected}')"
            errors=$(( errors + 1 ))
        fi
        if [[ "$published" != "false" ]]; then
            rehearsal_err "verify-evidence: negative scenario must record published: false"
            errors=$(( errors + 1 ))
        fi
        if [[ -z "$failed_job" ]]; then
            rehearsal_err "verify-evidence: negative scenario must name a failed_job"
            errors=$(( errors + 1 ))
        else
            # The failed job must precede publish-pypi in the workflow's
            # job order — a failure after publish is not a negative result.
            local order_ok=0 job
            while IFS= read -r job; do
                if [[ "$job" == "$REHEARSAL_PUBLISH_JOB" ]]; then
                    break
                fi
                if [[ "$job" == "$failed_job" ]]; then
                    order_ok=1
                fi
            done < <(rehearsal_release_job_order)
            if (( ! order_ok )); then
                rehearsal_err "verify-evidence: failed_job '${failed_job}' does not precede ${REHEARSAL_PUBLISH_JOB} in the release workflow job order"
                errors=$(( errors + 1 ))
            fi
        fi
    elif [[ "$scenario" == "leg2-dry-run" ]]; then
        if [[ "$expected" != "success" ]]; then
            rehearsal_err "verify-evidence: leg2-dry-run must expect success (got '${expected}')"
            errors=$(( errors + 1 ))
        fi
    fi

    if (( errors )); then
        rehearsal_err "verify-evidence: FAIL — ${errors} problem(s) in $file"
        return 1
    fi
    echo "verify-evidence: OK — $file (scenario: ${scenario})"
    return 0
}

# ---------------------------------------------------------------------------
# Executable entry point: offline evidence re-check.
# ---------------------------------------------------------------------------

_rehearsal_lib_usage() {
    cat <<'EOF'
usage: lib.sh --verify-evidence <evidence-file>

Offline re-check of a rehearsal evidence file (docs/rehearsal/
evidence-*.md). No network calls. Exit 0 iff the evidence is well-formed
and internally consistent per Ctl/rehearsal/README.md.
EOF
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
    set -euo pipefail
    case "${1:-}" in
        --verify-evidence)
            if [[ $# -ne 2 ]]; then
                _rehearsal_lib_usage >&2
                exit 2
            fi
            rehearsal_verify_evidence "$2"
            ;;
        -h|--help)
            _rehearsal_lib_usage
            ;;
        *)
            _rehearsal_lib_usage >&2
            exit 2
            ;;
    esac
fi
